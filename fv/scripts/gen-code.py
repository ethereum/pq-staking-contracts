#!/usr/bin/env python3
"""Writes fv/LeanXmssFv/Code/, the runtime bytecode of the contracts the proofs are about.

Each contract's runtime bytecode, as `forge build` writes it to contracts/out/, becomes one Lean file that holds it as one
number, the first byte highest, which is how EthLib's `NatCode.ofNat` stores a code. The proofs run that code on
EthLib's EVM, so these files are what ties them to the deployed bytes.

Run it from anywhere, after `forge build` in contracts/: `python3 fv/scripts/gen-code.py`. With `--check` it writes
nothing and fails if a file differs from what it would write, which is what CI runs.
"""

import json
import os
import sys

FV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARTIFACTS = os.path.join(os.path.dirname(FV), "contracts/out")
OUTPUT = os.path.join(FV, "LeanXmssFv/Code")

# The Lean module of each contract, and its artifact under contracts/out/.
CONTRACTS = [
    ("Harness", "LeanXmss.t.sol/LeanXmssHarness.json", "LeanXmssHarness"),
    ("Validator", "PQValidatorRegistration.sol/PQValidatorRegistration.json", "PQValidatorRegistration"),
    ("Builder", "PQBuilderRegistration.sol/PQBuilderRegistration.json", "PQBuilderRegistration"),
]

TEMPLATE = """\
module

public import EthLib.Execution.Proofs.Evm.Logic.NatCode

/-!
# The runtime bytecode of `{contract}`

Generated by `fv/scripts/gen-code.py` from the artifact that `forge build` writes. Do not edit.
-/

@[expose] public section

namespace LeanXmssFv.Code.{module}

open EthLib.Execution.Evm.Logic

/-- The size of the code, in bytes. -/
def SIZE : Nat := {size}

/-- The code as one number, the first byte highest. -/
def NUMBER : Nat :=
  0x{hex}

/-- The runtime bytecode of `{contract}`. -/
def CODE : ByteArray := NatCode.ofNat NUMBER SIZE

end LeanXmssFv.Code.{module}
"""


def runtime_code(artifact):
    """The runtime bytecode of a forge artifact, as bytes."""
    path = os.path.join(ARTIFACTS, artifact)
    if not os.path.exists(path):
        sys.exit(f"no {os.path.relpath(path)}: run `forge build` in contracts/ first")
    with open(path) as f:
        deployed = json.load(f)["deployedBytecode"]
    # A library to link or an immutable would leave bytes that the deployment fills in.
    assert not deployed.get("linkReferences"), artifact
    assert not deployed.get("immutableReferences"), artifact
    return bytes.fromhex(deployed["object"].removeprefix("0x"))


def render(module, artifact, contract):
    code = runtime_code(artifact)
    return TEMPLATE.format(contract=contract, module=module, size=len(code), hex=code.hex())


def main():
    check = sys.argv[1:] == ["--check"]
    assert check or not sys.argv[1:], "usage: gen-code.py [--check]"
    stale = []
    for module, artifact, contract in CONTRACTS:
        text = render(module, artifact, contract)
        path = os.path.join(OUTPUT, f"{module}.lean")
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(os.path.relpath(path))
            continue
        os.makedirs(OUTPUT, exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
    if stale:
        sys.exit(f"{', '.join(stale)} out of date: run fv/scripts/gen-code.py")


if __name__ == "__main__":
    main()
